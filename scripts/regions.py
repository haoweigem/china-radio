# 预编译：按长度降序，长词优先匹配
_MATCH_ORDER = sorted(
    [(k, v) for k, v in {**PROVINCE_ALIASES, **CITY_TO_PROVINCE, **EN_CITY}.items()],
    key=lambda kv: -len(kv[0]),
)


def detect_province(name: str, group: str = "") -> str:
    """从电台名称（和来源分组）推断省级归属，无法判断时返回「其他」。"""
    n = (name or "").strip()

    # 名称前缀「北京-xx」「广东-xx」
    for sep in ("-", "－", "_"):
        if sep in n:
            head = n.split(sep, 1)[0].strip()
            if head in PROVINCE_ALIASES:
                return PROVINCE_ALIASES[head]
            if head in CITY_TO_PROVINCE:
                return CITY_TO_PROVINCE[head]

    # 央广 / 国际台
    if "CNR" in n.upper() or "CRI" in n.upper() or "CGTN" in n.upper():
        return "中央"

    # 地名包含匹配（长词优先）
    for key, prov in _MATCH_ORDER:
        if key.lower() in n.lower():
            return prov

    return "其他"


